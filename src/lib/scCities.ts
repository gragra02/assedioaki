// Nomes ordenados de todos os 295 municípios
export const SC_CITIES_NAMES: string[] = SC_CITIES_DATA.map(c => c.name).sort((a, b) => 
  a.localeCompare(b, 'pt-BR', { sensitivity: 'base' })
);

// Mapa de coordenadas [latitude, longitude]
export const SC_CITY_COORDINATES_MAP: Record<string, [number, number]> = Object.fromEntries(
  SC_CITIES_DATA.map(c => [c.name, [c.lat, c.lng] as [number, number]])
);

// Obter coordenadas de uma cidade ou retornar o centro de Florianópolis
export const getCityCoordinates = (cityName: string): [number, number] => {
  if (SC_CITY_COORDINATES_MAP[cityName]) {
    return SC_CITY_COORDINATES_MAP[cityName];
  }
  // Busca flexível sem acento ou case-insensitive
  const normalized = cityName.trim().toLowerCase();
  const found = SC_CITIES_DATA.find(c => 
    c.name.toLowerCase() === normalized ||
    c.name.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase() === 
    normalized.normalize('NFD').replace(/[\u0300-\u036f]/g, '')
  );
  if (found) {
    return [found.lat, found.lng];
  }
  return [-27.5954, -48.5480]; // Padrão: Florianópolis
};
